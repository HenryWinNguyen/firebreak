"""Render ``evals/REPORT.md`` from the stored eval results (latest run per agent)."""

import os
import tempfile
from collections.abc import Mapping, Sequence
from pathlib import Path

from firebreak.db.repositories import EvalResult, EvalRun
from firebreak.evals.grader import Grade, summarize
from firebreak.evals.scenario import Scenario

DEFAULT_REPORT = Path("evals/REPORT.md")

Runs = Sequence[tuple[EvalRun, Sequence[EvalResult]]]


class NoRunsError(Exception):
    """There is no stored eval run to report on."""


def _mark(ok: bool) -> str:
    return "yes" if ok else "NO"


def _pct(x: float) -> str:
    return f"{x * 100:.0f}%"


def _cell(text: str) -> str:
    """One table cell: no pipes or newlines."""
    return text.replace("|", "\\|").replace("\n", " ")


def _grade(r: EvalResult) -> Grade:
    return Grade(
        top1=r.top1,
        top3=r.top3,
        cited_kinds_ok=r.cited_kinds_ok,
        report_valid=r.report_valid,
        cost_usd=r.cost_usd,
        latency_s=r.latency_s,
        error=r.error,
    )


def _expected(scenarios: Mapping[str, Scenario], scenario_id: str) -> str:
    s = scenarios.get(scenario_id)
    return "?" if s is None else s.expect.root_cause_category.value


def render_report(runs: Runs, scenarios: Mapping[str, Scenario]) -> str:
    """Markdown for the latest run of each agent. Deterministic for the same inputs."""
    if not runs:
        raise NoRunsError("no eval runs stored; run `make eval` first")
    lines = [
        "# Eval report",
        "",
        "Generated by `python -m firebreak.evals report` from the `eval_runs` / `eval_results` "
        "tables (latest run per agent). Do not edit by hand.",
    ]
    for run, results in sorted(runs, key=lambda x: x[0].agent):
        ordered = sorted(results, key=lambda r: r.scenario_id)
        lines += [
            "",
            f"## Agent: {run.agent}",
            "",
            f"- Run `{run.id}` ({run.mode}), started {run.started_at:%Y-%m-%d %H:%M} UTC",
            f"- Git `{(run.git_sha or 'unknown')[:12]}`, prompt sha256 "
            f"`{(run.prompt_sha256 or 'unknown')[:12]}`",
            "",
            "| Scenario | Expected | Top-1 | Top-3 | Cited kinds | Valid "
            "| Cost USD (recorded live run) | Latency s (recorded live run) | Steps | Error |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for r in ordered:
            lines.append(
                f"| {_cell(r.scenario_id)} | {_expected(scenarios, r.scenario_id)} "
                f"| {_mark(r.top1)} | {_mark(r.top3)} | {_mark(r.cited_kinds_ok)} "
                f"| {_mark(r.report_valid)} | {r.cost_usd:.4f} | {r.latency_s:.1f} | {r.steps} "
                f"| {_cell(r.error or '')} |"
            )
        if ordered:
            s = summarize([_grade(r) for r in ordered])
            lines += [
                "",
                f"**Summary ({s.n} scenarios):** top-1 {_pct(s.top1_accuracy)}, "
                f"top-3 {_pct(s.top3_accuracy)}, "
                f"latency (recorded live run) p50 {s.latency_p50_s:.1f}s / "
                f"p95 {s.latency_p95_s:.1f}s, "
                f"cost (recorded live run) p50 ${s.cost_p50_usd:.4f} / p95 ${s.cost_p95_usd:.4f}, "
                f"{s.error_count} errored.",
            ]
        else:
            lines += ["", "No scenarios in this run."]
    return "\n".join(lines) + "\n"


def write_report(text: str, path: Path = DEFAULT_REPORT) -> Path:
    """Write atomically so an interrupted run never leaves a half-written report."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    return path
